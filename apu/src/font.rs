/// Returns 128 tiles of 8x8 pixels (1 = ink, 0 = transparent).
pub fn character_rom() -> Vec<[u8; 64]> {
    let mut tiles = vec![[0u8; 64]; 128];
    for (code, rows) in GLYPHS {
        let t = &mut tiles[*code as usize];
        for (y, row) in rows.iter().enumerate() {
            for (x, ch) in row.bytes().enumerate() {
                if ch == b'#' {
                    t[y * 8 + x + 1] = 1;
                }
            }
        }
    }
    for c in b'a'..=b'z' {
        tiles[c as usize] = tiles[(c - 32) as usize];
    }
    tiles[127] = [1; 64];
    tiles
}
